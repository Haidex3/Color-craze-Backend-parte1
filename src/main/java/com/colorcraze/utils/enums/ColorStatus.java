package com.colorcraze.utils.enums;

/**
 * Represents the possible colors for players or platforms in the game.
 * 
 * WHITE   - Default or empty platform color.
 * YELLOW  - Player or platform color option.
 * RED     - Player or platform color option.
 * PURPLE  - Player or platform color option.
 * GREEN   - Default background color of the board.
 */
public enum ColorStatus {
    WHITE,
    YELLOW,
    RED,
    PURPLE,
    GREEN,
}