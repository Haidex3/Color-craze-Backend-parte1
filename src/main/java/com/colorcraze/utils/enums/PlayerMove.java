package com.colorcraze.utils.enums;

/**
 * Represents the possible movement directions for a player on the board.
 * 
 * RIGHT - Move the player one column to the right.
 * LEFT  - Move the player one column to the left.
 * UP    - Move the player one row up.
 * DOWN  - Move the player one row down.
 */
public enum PlayerMove {
    RIGHT,
    LEFT,
    UP,
    DOWN
}
